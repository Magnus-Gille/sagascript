//! Which commands write settings, found from the sources (#370).
//!
//! `commands/persist_tests.rs` wants a table row for every command that writes
//! settings. A list of names would miss a writer with another name, so this
//! scans the app's sources for them, with `syn`, like the CommandMap generator.
//!
//! A function **writes settings** when it calls `persist_and_sync`,
//! `try_persist_and_mirror` or `try_persist_and_replace` (commands/persist.rs),
//! or another function that does. A **command** that does is reported; so is
//! any function that calls the settings store's writers itself
//! ([`STORE_WRITERS`], [`MACHINE_WRITERS`]) instead of going through persist.rs.
//!
//! What the scan covers:
//! - every `.rs` file under `src/` except `*_tests.rs`, `test_fixtures.rs`,
//!   `commands/persist.rs` (the entry points and the store write live there) and
//!   this test-only `contract/` module;
//! - free functions, `impl` methods and default trait methods;
//! - calls by path (`persist_and_sync(…)`, `crate::overlay::apply()`), method
//!   calls (`saver.save()`), functions named as values (`.map(apply)`) and
//!   everything inside a macro invocation (`dbg!(…)`, `info!(…)`), whose tokens
//!   are read for an identifier followed by a parenthesis;
//! - `use … as …` renames, plain imports and module renames, per file.
//!
//! What it does not cover:
//! - Functions and methods are matched by **name** across all files, not by
//!   module path or receiver type. Two functions with one name are one node, so
//!   the scan can ask for a table row a command does not need, never the
//!   opposite.
//! - Glob imports (`use x::*`) are not resolved: a renamed or store-writing
//!   function reached only through one is missed.
//! - Code generated by `macro_rules!` is not expanded; a turbofish
//!   (`f::<T>(…)`) inside a macro invocation hides the call; calls through a
//!   function pointer or closure stored in a variable or a struct are not
//!   followed.
//! - Writes that do not go through the store (`std::fs` on the settings file) are
//!   not recognised.

use std::collections::{BTreeMap, BTreeSet};
use std::path::PathBuf;

use syn::ext::IdentExt;
use syn::parse::{ParseStream, Parser};
use syn::visit::Visit;
use syn::{Ident, ImplItemFn, ItemFn, Token, TraitItemFn, UseTree};

use super::command_map::{command_attribute, parse_file, rust_files, src_dir};

/// The functions that write settings.
#[derive(Debug, Default, PartialEq, Eq)]
pub(crate) struct SettingsWriters {
    /// `#[tauri::command]` functions that reach a persist entry point.
    pub commands: Vec<String>,
    /// Functions that call the settings store's writers themselves.
    pub bypassing: Vec<String>,
}

/// The persist entry points of `commands/persist.rs`.
const PERSIST_ENTRY_POINTS: &[&str] = &[
    "persist_and_sync",
    "try_persist_and_mirror",
    "try_persist_and_replace",
];
/// `settings::store`'s writers: `update` and `try_update` are re-exports of
/// `machine::{update, try_update}` (#448); the `_with` forms take the machine
/// probe, `save` and `save_to` write a given `Settings`.
const STORE_WRITERS: &[&str] = &[
    "update",
    "try_update",
    "update_with",
    "try_update_with",
    "save",
    "save_to",
    "save_over",
];
/// `machine`'s writers: the store's, with this machine's probes.
const MACHINE_WRITERS: &[&str] = &["update", "try_update"];

type Path = Vec<String>;
/// A name an import gives, and the full path it stands for.
type Imports = BTreeMap<String, Path>;

/// What one function calls, with imports resolved.
#[derive(Default)]
struct Function {
    is_command: bool,
    callees: BTreeSet<String>,
    writes_store: bool,
}

// -- imports --

fn collect_imports(tree: &UseTree, prefix: &mut Path, imports: &mut Imports) {
    match tree {
        UseTree::Path(path) => {
            prefix.push(path.ident.to_string());
            collect_imports(&path.tree, prefix, imports);
            prefix.pop();
        }
        UseTree::Name(name) => {
            let mut full = prefix.clone();
            full.push(name.ident.to_string());
            imports.insert(name.ident.to_string(), full);
        }
        UseTree::Rename(rename) => {
            let mut full = prefix.clone();
            full.push(rename.ident.to_string());
            imports.insert(rename.rename.to_string(), full);
        }
        UseTree::Glob(_) => {}
        UseTree::Group(group) => {
            for item in &group.items {
                collect_imports(item, prefix, imports);
            }
        }
    }
}

struct ImportCollector(Imports);

impl Visit<'_> for ImportCollector {
    fn visit_item_use(&mut self, item: &syn::ItemUse) {
        collect_imports(&item.tree, &mut Vec::new(), &mut self.0);
    }
}

/// `path` with its first segment replaced by what the file imported under that
/// name.
fn resolve(path: &[String], imports: &Imports) -> Path {
    match path.split_first() {
        Some((first, rest)) => match imports.get(first) {
            Some(full) => full.iter().chain(rest).cloned().collect(),
            None => path.to_vec(),
        },
        None => Vec::new(),
    }
}

// -- calls --

/// Every path a function body names where it could be called: calls, method
/// calls, functions used as values, and the same inside macro invocations.
#[derive(Default)]
struct Mentions(Vec<Path>);

impl Visit<'_> for Mentions {
    fn visit_expr_path(&mut self, expr: &syn::ExprPath) {
        self.0.push(
            expr.path
                .segments
                .iter()
                .map(|segment| segment.ident.to_string())
                .collect(),
        );
        syn::visit::visit_expr_path(self, expr);
    }

    fn visit_expr_method_call(&mut self, call: &syn::ExprMethodCall) {
        self.0.push(vec![call.method.to_string()]);
        syn::visit::visit_expr_method_call(self, call);
    }

    fn visit_macro(&mut self, mac: &syn::Macro) {
        // A macro's arguments are not syntax `syn` has parsed: read the tokens.
        // A body that is not a token sequence at all cannot be read; nothing is
        // reported for it.
        let reader = |input: ParseStream| read_macro_tokens(input, &mut self.0);
        let _ = reader.parse2(mac.tokens.clone());
        syn::visit::visit_macro(self, mac);
    }
}

/// Paths followed by a parenthesis, at any depth: `a::b(…)` and `.m(…)` both
/// look like that.
fn read_macro_tokens(input: ParseStream, found: &mut Vec<Path>) -> syn::Result<()> {
    let mut path: Path = Vec::new();
    let mut after_separator = false;
    while !input.is_empty() {
        if input.peek(Ident::peek_any) {
            let ident = input.call(Ident::parse_any)?;
            if !after_separator {
                path.clear();
            }
            path.push(ident.to_string());
            after_separator = false;
        } else if input.peek(Token![::]) {
            input.parse::<Token![::]>()?;
            after_separator = true;
        } else if input.peek(syn::token::Paren) {
            let content;
            syn::parenthesized!(content in input);
            if !path.is_empty() {
                found.push(std::mem::take(&mut path));
            }
            read_macro_tokens(&content, found)?;
            after_separator = false;
        } else if input.peek(syn::token::Bracket) {
            let content;
            syn::bracketed!(content in input);
            path.clear();
            read_macro_tokens(&content, found)?;
            after_separator = false;
        } else if input.peek(syn::token::Brace) {
            let content;
            syn::braced!(content in input);
            path.clear();
            read_macro_tokens(&content, found)?;
            after_separator = false;
        } else {
            // Punctuation, a literal or a lifetime: skip one token.
            input.step(|cursor| match cursor.token_tree() {
                Some((_, rest)) => Ok(((), rest)),
                None => Err(cursor.error("end of macro input")),
            })?;
            path.clear();
            after_separator = false;
        }
    }
    Ok(())
}

// -- functions --

struct Functions<'a> {
    imports: &'a Imports,
    table: &'a mut BTreeMap<String, Function>,
}

impl Functions<'_> {
    fn record(&mut self, name: &Ident, is_command: bool, block: &syn::Block) {
        let mut mentions = Mentions::default();
        mentions.visit_block(block);
        let entry = self.table.entry(name.to_string()).or_default();
        entry.is_command |= is_command;
        for path in mentions.0 {
            let resolved = resolve(&path, self.imports);
            if let [.., module, writer] = resolved.as_slice() {
                let store = module == "store" && STORE_WRITERS.contains(&writer.as_str());
                let machine = module == "machine" && MACHINE_WRITERS.contains(&writer.as_str());
                entry.writes_store |= store || machine;
            }
            if let Some(callee) = resolved.last() {
                entry.callees.insert(callee.clone());
            }
        }
    }
}

impl Visit<'_> for Functions<'_> {
    fn visit_item_fn(&mut self, function: &ItemFn) {
        let is_command = function
            .attrs
            .iter()
            .any(|attribute| matches!(command_attribute(attribute), Ok(true)));
        self.record(&function.sig.ident, is_command, &function.block);
        syn::visit::visit_item_fn(self, function);
    }

    fn visit_impl_item_fn(&mut self, function: &ImplItemFn) {
        self.record(&function.sig.ident, false, &function.block);
        syn::visit::visit_impl_item_fn(self, function);
    }

    fn visit_trait_item_fn(&mut self, function: &TraitItemFn) {
        if let Some(block) = &function.default {
            self.record(&function.sig.ident, false, block);
        }
        syn::visit::visit_trait_item_fn(self, function);
    }
}

/// The settings writers among `files` (parsed sources).
pub(super) fn analyse(files: &[syn::File]) -> SettingsWriters {
    let mut table: BTreeMap<String, Function> = BTreeMap::new();
    for file in files {
        let mut imports = ImportCollector(Imports::new());
        imports.visit_file(file);
        Functions {
            imports: &imports.0,
            table: &mut table,
        }
        .visit_file(file);
    }
    // A function writes settings when it calls an entry point or a function that
    // does; commands call other commands (`set_whisper_model` calls
    // `set_profile_model`).
    let mut writers: BTreeSet<&str> = BTreeSet::new();
    loop {
        let before = writers.len();
        for (name, function) in &table {
            if function.callees.iter().any(|callee| {
                PERSIST_ENTRY_POINTS.contains(&callee.as_str()) || writers.contains(callee.as_str())
            }) {
                writers.insert(name);
            }
        }
        if writers.len() == before {
            break;
        }
    }
    SettingsWriters {
        commands: table
            .iter()
            .filter(|(name, function)| function.is_command && writers.contains(name.as_str()))
            .map(|(name, _)| name.clone())
            .collect(),
        bypassing: table
            .iter()
            .filter(|(_, function)| function.writes_store)
            .map(|(name, _)| name.clone())
            .collect(),
    }
}

/// The files the scan reads, relative to nothing: absolute paths below `src/`.
pub(super) fn scanned_sources() -> Vec<PathBuf> {
    let root = src_dir();
    rust_files(&root)
        .into_iter()
        .filter(|path| {
            let relative = path
                .strip_prefix(&root)
                .map(|relative| relative.to_string_lossy().replace('\\', "/"))
                .unwrap_or_default();
            let name = relative.rsplit('/').next().unwrap_or_default();
            !name.ends_with("_tests.rs")
                && name != "test_fixtures.rs"
                && relative != "commands/persist.rs"
                && !relative.starts_with("contract/")
        })
        .collect()
}

pub(super) fn settings_writers() -> SettingsWriters {
    let files: Vec<syn::File> = scanned_sources()
        .iter()
        .map(|path| parse_file(path))
        .collect();
    analyse(&files)
}

